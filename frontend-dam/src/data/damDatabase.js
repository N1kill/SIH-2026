/**
 * Coordinate mapping for India SVG viewport (viewBox="0 0 612 696")
 * Fits real geographic lat/lng to precise vector paths of the 36 states/UTs
 */
export function latLngToSVG(lat, lng) {
  const x = -1335.21 + 19.7743 * lng + 0.3257 * lat;
  const y = 834.17 + 0.4847 * lng - 23.2203 * lat;
  return { x, y };
}

